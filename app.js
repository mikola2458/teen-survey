let idx = parseInt(localStorage.getItem("idx") || "0");
let answers = JSON.parse(localStorage.getItem("answers") || "{}");
let startTime = parseInt(localStorage.getItem("startTime") || Date.now());

if (!localStorage.getItem("startTime")) {
    localStorage.setItem("startTime", startTime);
}

/* =========================
   SESSION ID
========================= */

function getSessionId() {
    let id = localStorage.getItem("sessionId");
    if (!id) {
        id = crypto.randomUUID();
        localStorage.setItem("sessionId", id);
    }
    return id;
}

/* =========================
   UI ELEMENTS
========================= */

const app = document.getElementById("app");

/* =========================
   RENDER
========================= */

function render() {

    if (idx >= questions.length) {
        finish();
        return;
    }

    const progress = Math.round((idx / questions.length) * 100);

    const support =
        idx > 0 && idx % 10 === 0
            ? getSupportMessage()
            : "";

    app.innerHTML = `
        <div class="card">

            <div class="progress-header">
                <span>Вопрос ${idx + 1} из ${questions.length}</span>
                <span id="save-indicator">✓ Сохранено</span>
            </div>

            <div class="progress-track">
                <div class="progress-bar" style="width:${progress}%"></div>
            </div>

            ${support ? `<div class="support-message">${support}</div>` : ""}

            <div class="question-card">
                <div class="question-illustration">
    <svg class="svg-sprout" viewBox="0 0 120 120">
        <path class="stem" d="M60 100 C60 80, 60 70, 60 50" />
        <path class="leaf leaf-left" d="M60 70 C40 60, 35 45, 50 40 C60 50, 60 60, 60 70" />
        <path class="leaf leaf-right" d="M60 70 C80 60, 85 45, 70 40 C60 50, 60 60, 60 70" />
        <circle class="bud" cx="60" cy="45" r="6"/>
    </svg>
</div>
                <div class="question-text">${questions[idx]}</div>
            </div>

            <div class="answers">
                <button class="answer-btn answer-soft" onclick="answer(0)">😌 Никогда или редко</button>
                <button class="answer-btn answer-medium" onclick="answer(1)">🙂 Иногда</button>
                <button class="answer-btn answer-strong" onclick="answer(2)">😟 Часто или всегда</button>
            </div>
        </div>
    `;
}

/* =========================
   ОТВЕТ
========================= */

function answer(value) {
    answers[idx] = value;
    localStorage.setItem("answers", JSON.stringify(answers));

    idx++;
    localStorage.setItem("idx", idx);

    render();
}

/* =========================
   ПОДДЕРЖКА
========================= */

function getSupportMessage() {
    const messages = [
        "🌱 Спасибо, ты уже прошла часть опроса.",
        "💜 Осталось совсем немного.",
        "✨ Ты отлично справляешься."
    ];
    return messages[Math.floor(Math.random() * messages.length)];
}

/* =========================
   ЗАВЕРШЕНИЕ
========================= */

async function finish() {

    const duration = Math.round((Date.now() - startTime) / 1000);

    app.innerHTML = `
        <div class="card">
            <h1>Спасибо за ответы! 💜</h1>
            <p>Твои ответы успешно сохранены.</p>
        </div>
    `;

    try {
        await fetch(GOOGLE_SCRIPT_URL, {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
           mode: "no-cors",
            body: JSON.stringify({
                sessionId: getSessionId(),
                duration,
                answers
            })
        });

        localStorage.clear();

    } catch (e) {
        console.log("Send error:", e);
    }
}

/* =========================
   START
========================= */

render();
